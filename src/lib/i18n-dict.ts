export function isSupportedLocale(value: string | null | undefined): value is Locale {
  return value === 'en' || value === 'fr' || value === 'es' || value === 'ja' || value === 'zh'
}

export function detectLocale(preferredLanguages?: readonly string[]): Locale {
  const list = preferredLanguages ?? (typeof navigator !== 'undefined' ? (navigator.languages?.length ? navigator.languages : [navigator.language]) : [])
  for (const raw of list) {
    const code = String(raw || '').trim().toLowerCase().split(/[-_]/)[0]
    if (isSupportedLocale(code)) return code
  }
  return 'en'
}

